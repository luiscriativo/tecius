import { describe, expect, it } from 'vitest'
import { columnsOf, formatCoords, importanceStars, isStyledPreset, normalizeStyleName, normalizeTone, presetColumns, resolvePageStyle } from './pageStyle'

describe('estilos de página', () => {
  it('herda do evento para a timeline e para o vault; sem nada, clássico', () => {
    expect(resolvePageStyle(undefined, undefined, undefined)).toBe('classico')
    expect(resolvePageStyle(undefined, undefined, 'jornal')).toBe('jornal')
    expect(resolvePageStyle(undefined, 'jornal', 'classico')).toBe('jornal')
    expect(resolvePageStyle('classico', 'jornal', 'jornal')).toBe('classico')
    expect(resolvePageStyle('', 'meu-estilo', 'jornal')).toBe('meu-estilo')
  })
  it('normaliza nomes e sinônimos', () => {
    expect(normalizeStyleName(' Jornal ')).toBe('jornal')
    expect(normalizeStyleName('Newspaper')).toBe('jornal')
    expect(normalizeStyleName('Padrão')).toBe('classico')
    expect(normalizeStyleName('Scrapbook')).toBe('album')
    expect(normalizeStyleName('Álbum')).toBe('album')
    expect(normalizeStyleName('Field notebook')).toBe('campo')
    expect(normalizeStyleName('Dossier')).toBe('dossie')
    expect(normalizeStyleName('Manuscrito')).toBe('iluminura')
    expect(normalizeStyleName('Broadside')).toBe('cartaz')
    expect(normalizeStyleName('Airmail')).toBe('correio')
    expect(normalizeStyleName('Meu Estilo!')).toBe('meuestilo')
    expect(normalizeStyleName(42)).toBeNull()
  })
  it('presets pg, colunas por preset e coordenadas', () => {
    expect(isStyledPreset('campo')).toBe(true)
    expect(isStyledPreset('jornal')).toBe(false)
    expect(presetColumns('cartaz')).toBe(2)
    expect(presetColumns('correio')).toBe(1)
    expect(columnsOf(undefined, presetColumns('correio'))).toBe(1)
    expect(formatCoords(-23.545, -46.639)).toBe('23°33′S 46°38′O')
    expect(formatCoords(51.5, -0.12)).toBe('51°30′N 0°07′O')
    expect(formatCoords(0, 0)).toBe('0°00′N 0°00′L')
    expect(normalizeStyleName('Folha de rosto')).toBe('rosto')
    expect(normalizeStyleName('encyclopedia')).toBe('verbete')
    expect(normalizeStyleName('Gazette')).toBe('gazeta')
    expect(normalizeStyleName('diary')).toBe('diario')
    expect(normalizeStyleName('alvará')).toBe('decreto')
    expect(normalizeStyleName('magazine')).toBe('revista')
    expect(presetColumns('revista')).toBe(3)
    expect(presetColumns('verbete')).toBe(2)
    expect(isStyledPreset('decreto')).toBe(true)
    expect(normalizeTone('Escuro')).toBe('dark')
    expect(normalizeTone('light')).toBe('light')
    expect(normalizeTone('azul')).toBeUndefined()
    expect(normalizeTone(undefined)).toBeUndefined()
  })
  it('estrelas e colunas', () => {
    expect(importanceStars(4)).toBe('★★★★☆')
    expect(importanceStars(undefined)).toBe('☆☆☆☆☆')
    expect(columnsOf(undefined)).toBe(2)
    expect(columnsOf('3')).toBe(3)
    expect(columnsOf(7)).toBe(2)
  })
})
